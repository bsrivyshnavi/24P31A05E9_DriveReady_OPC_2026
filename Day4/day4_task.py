@tool(args_schema=ClothingOrder)
def log_order(
    customer_name: str,
    product: str,
    quantity: int,
    size: str,
    color: str
) -> str:
    """Save a confirmed customer clothing order to Google Sheets."""

    ws.append_row([
        customer_name,
        product,
        quantity,
        size,
        color
    ])

    return "Order saved successfully"

