from langchain_core.tools import tool

PRICES = {
    "shirt": 500,
    "jeans": 1200,
    "tshirt": 400,
    "jacket": 1500
}

@tool
def check_price(product: str) -> str:
    """Find the unit price of a clothing product in rupees."""

    price = PRICES.get(product.lower())

    if price is None:
        return "Product not available"

    return str(price)


@tool
def calculate_total(price: int, quantity: int) -> int:
    """Calculate the total cost using unit price and quantity."""

    return price * quantity

print(check_price.invoke({"product": "shirt"}))

print(calculate_total.invoke({
    "price": 500,
    "quantity": 3
}))

