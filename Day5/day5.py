def inspect_agent(question):

    config = {
        "configurable": {
            "thread_id": str(uuid.uuid4())
        }
    }

    result = agent.invoke(
        {
            "messages": [
                {
                    "role": "user",
                    "content": question
                }
            ]
        },
        config=config
    )

    model_calls = 0

    print("Question:", question)

    for message in result["messages"]:

        if message.type == "ai":

            model_calls += 1

            for call in message.tool_calls:
                print("Tool selected:", call["name"])
                print("Arguments:", call["args"])

        elif message.type == "tool":
            print("Tool output:", message.content)

    print("Model calls:", model_calls)

    print("Final answer:",
          result["messages"][-1].content)

    print("-" * 50)

