from pydantic import BaseModel, Field
from datetime import date as Date

class Order(BaseModel):
    name: str = Field(min_length=1)
    item: str
    qty: int = Field(gt=0)
    date: Date
    eggless: bool


@tool
def log_order(
    name: str,
    item: str,
    qty: int,
    date: str,
    eggless: bool
) -> str:
    """Save a confirmed customer order in Google Sheets.
    Date must be in YYYY-MM-DD format.
    Use only after the customer confirms all details."""

    try:
        order = Order(
            name=name,
            item=item.lower().strip(),
            qty=qty,
            date=date,
            eggless=eggless
        )

        if order.item not in MENU:
            return "Invalid bakery item."

        total = MENU[order.item] * order.qty

        ws.append_row([
            order.name,
            order.item,
            order.qty,
            str(order.date),
            order.eggless,
            total
        ])

        return f"Order saved successfully. Total: Rs {total}"

    except Exception as e:
        return f"Order could not be saved: {e}"


