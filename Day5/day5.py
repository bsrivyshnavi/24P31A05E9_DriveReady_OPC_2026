def run_tests():

    df = pd.read_csv("day5_tests.csv")

    passed = 0
    results = []

    for _, row in df.iterrows():

        question = row["question"]
        expected = str(row["expected"])

        try:
            answer = chat(
                str(uuid.uuid4()),
                question
            )

            success = expected.lower() in answer.lower()

        except Exception as e:
            answer = str(e)
            success = False

        if success:
            passed += 1

        results.append({
            "question": question,
            "expected": expected,
            "actual": answer,
            "result": "PASS" if success else "FAIL"
        })

    total = len(df)
    pass_rate = passed / total * 100

    report = pd.DataFrame(results)

    display(report)

    report.to_csv(
        "day5_test_results.csv",
        index=False
    )

    print("Total tests:", total)
    print("Passed:", passed)
    print("Failed:", total - passed)
    print(f"Pass rate: {pass_rate:.2f}%")

    if pass_rate >= 80:
        print("Target achieved!")
    else:
        print("Improve the agent and retest.")


