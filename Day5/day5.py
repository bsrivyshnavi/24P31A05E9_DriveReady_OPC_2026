def chat(thread_id: str, text: str) -> str:

    config = {
        "configurable": {
            "thread_id": thread_id
        }
    }

    result = agent.invoke(
        {
            "messages": [
                {
                    "role": "user",
                    "content": text
                }
            ]
        },
        config=config
    )

    return result["messages"][-1].content

